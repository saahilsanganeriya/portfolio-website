// Writes src/lib/poster-glyphs.ts: the outlines renderPoster() sets type with, so a poster drawn in the browser
// is one self-contained SVG (an <img> or a texture cannot load web fonts) in the same faces as the hand-drawn set.
// Usage: node scripts/posters/glyphs.mjs (rerun only when the character sets or fonts change).
import { openSync } from 'fontkit';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const font = (pkg, file) => openSync(fileURLToPath(new URL(`../../node_modules/${pkg}/files/${file}`, import.meta.url)));
const gothic = font('@fontsource-variable/league-gothic', 'league-gothic-latin-wdth-normal.woff2');
const serif = font('@fontsource-variable/newsreader', 'newsreader-latin-opsz-normal.woff2');
const serifItalic = font('@fontsource-variable/newsreader', 'newsreader-latin-standard-italic.woff2');

const ACCENTED_CAPS = 'ÀÁÂÃÄÅÆÇÈÉÊËÌÍÎÏÐÑÒÓÔÕÖØÙÚÛÜÝÞŒŠŽŸ';
const PUNCTUATION = ' .,:;!?\'’"“”&-–—()/';
const TITLE_CHARS = `ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789${PUNCTUATION}${ACCENTED_CAPS}`;
const NAME_CHARS =
  `ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,'’-–&()${ACCENTED_CAPS}` +
  'àáâãäåæçèéêëìíîïðñòóôõöøùúûüýþÿœšžß';
// Kerning only for the title face's capitals and digits: at the credit line's 19 units Newsreader's pairs move a
// glyph by a tenth of a pixel and would triple the table.
const TITLE_KERN_CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
const KERN_MIN = 6;

const rounded = (d) => d.replace(/-?\d+(\.\d+)?/g, (v) => String(Math.round(Number(v))));
const pathOf = (glyph) => rounded(glyph.path.toSVG());

function table(face, chars, kernChars, features = []) {
  const glyphs = {};
  for (const ch of chars) {
    if (!face.hasGlyphForCodePoint(ch.codePointAt(0))) continue;
    const [glyph] = face.layout(ch, features).glyphs;
    glyphs[ch] = [Math.round(glyph.advanceWidth), pathOf(glyph)];
  }
  const kern = {};
  for (const a of kernChars) {
    for (const b of kernChars) {
      const run = face.layout(a + b, features);
      const delta = Math.round(run.positions[0].xAdvance - run.glyphs[0].advanceWidth);
      if (Math.abs(delta) >= KERN_MIN) kern[a + b] = delta;
    }
  }
  return { unitsPerEm: face.unitsPerEm, capHeight: face.capHeight, glyphs, kern };
}

const byline = serifItalic.layout('a film by');
let pen = 0;
const bylineParts = byline.glyphs.map((glyph, i) => {
  const d = rounded(glyph.path.translate(pen, 0).toSVG());
  pen += byline.positions[i].xAdvance;
  return d;
});

const data = {
  gothic: table(gothic, TITLE_CHARS, TITLE_KERN_CHARS),
  // Old-style figures for the year, as on the hand-drawn sheets.
  serif: table(serif, NAME_CHARS, '', ['onum']),
  byline: { unitsPerEm: serifItalic.unitsPerEm, advance: Math.round(pen), d: bylineParts.join('') },
};

const out = `// Generated by scripts/posters/glyphs.mjs from League Gothic and Newsreader (SIL OFL 1.1, see blender/ASSETS.md).
// Font units, y up. Do not edit by hand; rerun the script.
export interface GlyphFace {
  unitsPerEm: number;
  capHeight: number;
  glyphs: Record<string, readonly [advance: number, path: string]>;
  kern: Record<string, number>;
}

export const GLYPHS: { gothic: GlyphFace; serif: GlyphFace; byline: { unitsPerEm: number; advance: number; d: string } } = ${JSON.stringify(data)};
`;
await writeFile(new URL('../../src/lib/poster-glyphs.ts', import.meta.url), out);
const counts = (t) => `${Object.keys(t.glyphs).length} glyphs, ${Object.keys(t.kern).length} kern pairs`;
console.log(`glyphs: gothic ${counts(data.gothic)}; serif ${counts(data.serif)}; ${out.length} B`);
